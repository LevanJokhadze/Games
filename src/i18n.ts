export const dicts: Record<Lang, Dict> = { en, ka };

export type T = (key: Exclude<keyof Dict, "rulesText">, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  return (key, vars) => {
    let s = dicts[lang][key] as string;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

